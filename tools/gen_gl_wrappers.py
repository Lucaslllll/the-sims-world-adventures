#!/usr/bin/env python3
"""Generate exports from the port's canonical gl_funcs.inc signature table."""
from pathlib import Path
import re
import sys

INTERCEPTED = {
    "glCompressedTexImage2D", "glCompressedTexSubImage2D", "glFramebufferRenderbuffer",
    "glFramebufferRenderbufferOES", "glShaderSource", "glGetError", "glTexImage2D", "glTexSubImage2D",
    "glDeleteTextures", "glViewport", "glScissor", "glBindFramebuffer", "glBindFramebufferOES",
    "glGetIntegerv", "glGetFloatv", "glRenderbufferStorage", "glRenderbufferStorageOES",
    "glGetRenderbufferParameteriv", "glGetRenderbufferParameterivOES",
    "glDeleteRenderbuffers", "glDeleteRenderbuffersOES",
}


def generate(directory):
    signatures = []
    for line in (directory / "gl_funcs.inc").read_text().splitlines():
        match = re.match(r"\s*X\((\w+),\s*([^,]+),\s*\((.*)\)\)\s*\\?\s*$", line)
        if match:
            signatures.append(match.groups())
    if not signatures or not INTERCEPTED.issubset({s[0] for s in signatures}):
        raise ValueError("Incomplete GL signature table")
    lines = ["// Generated by tools/gen_gl_wrappers.py - do not edit.", ""]
    for name, result, params in signatures:
        if name in INTERCEPTED:
            continue
        args = "" if params == "void" else ", ".join(p.replace("*", " ").split()[-1] for p in params.split(","))
        call = f"gl::fn.{name}({args})"
        body = ("return " if result != "void" else "") + call + ";"
        lines.append(f'static {result} w_{name}({params}) {{ GLTRACE("{name}"); {body} }}')
    lines.append("")
    for name, _, _ in signatures:
        lines.append(f"HLE_EXPORT({name}, {'h_' if name in INTERCEPTED else 'w_'}{name});")
    (directory / "gl_exports.inc").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    generate(Path(sys.argv[1]))
